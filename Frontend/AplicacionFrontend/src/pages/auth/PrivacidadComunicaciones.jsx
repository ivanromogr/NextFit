import { useEffect, useRef, useState } from "react";
import { getConsents, updateMarketingConsent } from "../../api/endpoints";
import { useAuth } from "../../context/AuthContext";

const date = (value) => value && Number.isFinite(new Date(value).getTime())
  ? new Date(value).toLocaleString() : "No disponible";
const missing = (consent) => consent?.status === "LEGACY_MISSING";
const valid = (data) => data && [data.terms, data.privacy, data.marketing]
  .every(consent => consent && (missing(consent) || typeof consent.accepted === 'boolean'));

export default function PrivacidadComunicaciones() {
  const { userId } = useAuth();
  return <ConsentPreferences key={userId || 'anonymous'} userId={userId} />;
}

function ConsentPreferences({ userId }) {
  const [consents, setConsents] = useState(null);
  const [message, setMessage] = useState("");
  const [saving, setSaving] = useState(false);
  const [loadError, setLoadError] = useState(false);
  const [revision, setRevision] = useState(0);
  const request = useRef({ active: true, pending: false });
  useEffect(() => {
    const current = request.current;
    current.active = true;
    return () => { current.active = false; };
  }, []);
  useEffect(() => {
    if (!userId) return;
    let active = true;
    setConsents(null); setLoadError(false); setMessage('');
    getConsents().then(({ data }) => {
      if (!valid(data)) throw new Error('Invalid consent response');
      if (active) setConsents(data);
    }).catch(() => { if (active) setLoadError(true); });
    return () => { active = false; };
  }, [userId, revision]);
  const toggleMarketing = async (event) => {
    if (!consents || !request.current.active || request.current.pending) return;
    const accepted = event.target.checked;
    request.current.pending = true;
    setSaving(true); setMessage("");
    try {
      await updateMarketingConsent(accepted);
      if (!request.current.active) return;
      // Acknowledgement confirms the value, not timestamps generated by this browser.
      setConsents((current) => ({ ...current, marketing: { ...current.marketing, accepted } }));
      setMessage("Preferencia de marketing actualizada.");
    } catch {
      if (request.current.active) setMessage("No se pudo actualizar la preferencia de marketing.");
    } finally {
      request.current.pending = false;
      if (request.current.active) setSaving(false);
    }
  };
  const item = (name, consent) => <li><strong>{name}:</strong> {missing(consent) ? "Sin consentimiento histórico registrado" : <>versión {consent.version || "No disponible"}. Fecha: {date(consent.acceptedAt)}</>}</li>;
  return <section aria-labelledby="privacy-communications-title">
    <h2 id="privacy-communications-title">Privacidad y comunicaciones</h2>
    <p>Los términos y la política se consultan aquí; sólo puedes modificar las comunicaciones de marketing.</p>
    {userId && !consents && !loadError && <p role="status">Cargando configuración de privacidad…</p>}
    {loadError && <div role="alert"><p>No se pudo cargar la configuración de privacidad.</p><button type="button" onClick={() => setRevision(n => n + 1)}>Reintentar privacidad</button></div>}
    {message && <p role="status">{message}</p>}
    {consents && <ul>{item("Términos de uso", consents.terms)}{item("Política de privacidad", consents.privacy)}</ul>}
    <label>
      <input aria-label="Comunicaciones de marketing" type="checkbox" checked={Boolean(consents?.marketing?.accepted)} disabled={!consents || saving} onChange={toggleMarketing} />
      Recibir comunicaciones de marketing
    </label>
    {consents?.marketing && <p>Marketing: {consents.marketing.accepted ? "activado" : "desactivado"}.</p>}
  </section>;
}
